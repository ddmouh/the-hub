    public static IntPtr RegisterUsbDeviceNotification(IntPtr hWnd)
    {
        try
        {
            var di = new DEV_BROADCAST_DEVICEINTERFACE
            {
                dbcc_size = Marshal.SizeOf(typeof(DEV_BROADCAST_DEVICEINTERFACE)),
                dbcc_devicetype = DBT_DEVTYP_DEVICEINTERFACE,
                dbcc_reserved = 0,
                dbcc_classguid = GUID_DEVINTERFACE_USB_DEVICE
            };

            IntPtr buffer = Marshal.AllocHGlobal(di.dbcc_size);
            Marshal.StructureToPtr(di, buffer, true);
            IntPtr hDevNotify = RegisterDeviceNotification(hWnd, buffer, DEVICE_NOTIFY_WINDOW_HANDLE);
            Marshal.FreeHGlobal(buffer);
            return hDevNotify;
        }
        catch
        {
            return IntPtr.Zero;
        }
    }

